"""Export the trained LightGBM trust scorer (backend/models/trust_lgbm.txt) to a compact JSON/JS module so the
SAME trained model runs in the browser (GitHub Pages, no backend). Validated against lightgbm on real dataset rows."""
import json, re, sys, math, pathlib
import numpy as np
root = pathlib.Path(__file__).resolve().parent.parent
txt = (root / 'backend/models/trust_lgbm.txt').read_text()
trees = []
for blk in re.split(r'\n(?=Tree=\d+)', txt)[1:]:
    blk = blk.split('\n\n')[0]
    kv = dict(l.split('=', 1) for l in blk.splitlines()[1:] if '=' in l)
    f = lambda k, c=float: [c(x) for x in kv[k].split()] if k in kv and kv[k].strip() else []
    trees.append(dict(sf=f('split_feature', int), th=[round(x, 9) for x in f('threshold')], dt=f('decision_type', int),
                      lc=f('left_child', int), rc=f('right_child', int), lv=[round(x, 7) for x in f('leaf_value')]))
meta = json.loads((root / 'backend/models/trust_meta.json').read_text())
out = dict(features=meta['features'], trees=trees, auc=meta['metrics']['auc_lgbm'], auc_heuristic=meta['metrics']['auc_heuristic'], n_train=meta['metrics']['n_fit'])
js = '/* AUTO-GENERATED by scripts/export_trust_js.py from backend/models/trust_lgbm.txt - do not edit */\nconst TRUST_MODEL=' + json.dumps(out, separators=(',', ':')) + ';\n'
js += '''function trustPredict(x){ /* x: array of 14 features in TRUST_MODEL.features order -> P(reading is trustworthy) */
  let s=0; const T=TRUST_MODEL.trees;
  for(let t=0;t<T.length;t++){ const tr=T[t]; if(!tr.sf.length){ s+=tr.lv[0]; continue; } let n=0;
    for(;;){ let v=x[tr.sf[n]]; const d=tr.dt[n], mt=(d>>2)&3, nan=v!==v; if(nan&&mt!==2) v=0;
      const dflt=(mt===1&&v>=-1e-35&&v<=1e-35)||(mt===2&&nan); const left=dflt?(d&2)!==0:v<=tr.th[n];
      const c=left?tr.lc[n]:tr.rc[n]; if(c<0){ s+=tr.lv[~c]; break; } n=c; } }
  return 1/(1+Math.exp(-s)); }
if(typeof module!=='undefined')module.exports={TRUST_MODEL,trustPredict};
'''
(root / 'src/trust_model.js').write_text(js)
print('trees', len(trees), 'bytes', len(js))
